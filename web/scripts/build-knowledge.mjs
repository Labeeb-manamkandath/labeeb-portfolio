// Builds what the chat buddy knows: the text of the built pages (home, about, approach,
// projects) and every case study, plus the links it may share. Run after `npm run build`:
//   node scripts/build-knowledge.mjs   → writes ../api/_knowledge.js (committed)
import { readFileSync, writeFileSync } from "node:fs";
import { PROJECTS } from "../src/data/projects.js";

const dist = (p) => readFileSync(new URL(`../dist/${p}`, import.meta.url), "utf8");
const text = (html) =>
  html
    .replace(/<(script|style|svg|nav|header)[\s\S]*?<\/\1>/gi, " ")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/(p|h[1-6]|li|div|section|dt|dd)>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, " ")
    .replace(/[ \t]+/g, " ").replace(/\n\s*/g, "\n").replace(/\n{2,}/g, "\n").trim();
const main = (html) => text((html.match(/<main[\s\S]*?<\/main>/) || [html])[0]);

const pages = [
  ["Homepage (/)", "index.html"],
  ["About page (/about)", "about/index.html"],
  ["Approach page (/approach)", "approach/index.html"],
].map(([t, f]) => `## ${t}\n${main(dist(f))}`);

const cases = PROJECTS.map((p) => {
  const raw = readFileSync(new URL(`../src/data/cases/${p.key}.html`, import.meta.url), "utf8");
  return `## Case study: ${p.title} (/work/${p.key})\n${p.cat}, ${p.yr}. ${p.sum}\n${text(raw).replace(/^← All projects\s*/, "")}`;
});

const contact = text(dist("about/index.html").match(/<section[^>]*id="contact"[\s\S]*?<\/section>/)[0]);

const links = [
  { href: "/", label: "Homepage" },
  { href: "/#demos", label: "AI demos" },
  { href: "/#voice", label: "Voice notes demo" },
  { href: "/#face", label: "Face registration demo" },
  { href: "/#workforce", label: "Time & attendance" },
  { href: "/#talk", label: "Toolbox Talk demo" },
  { href: "/projects", label: "All projects" },
  { href: "/about", label: "About Labeeb" },
  { href: "/about#experience", label: "Experience" },
  { href: "/approach", label: "How he designs AI" },
  ...PROJECTS.map((p) => ({ href: `/work/${p.key}`, label: `${p.title} case study` })),
  { href: "https://www.linkedin.com/in/labeeb-manamkandath/", label: "LinkedIn" },
  { href: "https://drive.google.com/file/d/1T2q3xYoZ1Y3RMQuTSOXnXOsSAmCl3WTx/view?usp=sharing", label: "Resume" },
  { href: "mailto:labeebmanamkandath@gmail.com", label: "Email Labeeb" },
];

const knowledge = `# Labeeb Manamkandath's portfolio (labeebs.com)\n\n${pages.join("\n\n")}\n\n## Contact\n${contact}\n\n${cases.join("\n\n")}`;
writeFileSync(
  new URL("../../api/_knowledge.js", import.meta.url),
  `// Generated by web/scripts/build-knowledge.mjs from the site's own pages. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\nexport const LINKS = ${JSON.stringify(links, null, 2)};\n`,
);
console.log("knowledge chars:", knowledge.length, "links:", links.length);
